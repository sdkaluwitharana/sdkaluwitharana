def stack():
    parts = []
    for group, items in STACK:
        tiles = "\n".join(
            f'  <a href="{escape(with_ref(url))}" title="{escape(label)}"><img src="./assets/stack/{slug(label)}.svg" '
            f'width="88" alt="{escape(label)}" /></a>'
            for _, label, url, _, _ in items)
        parts.append(f"**`{group}`**\n\n<p align=\"left\">\n{tiles}\n</p>")
    return "\n\n".join(parts)


def projects():
    def a(p):
        slug_, title, domain, url = p[:4]
        return (f'<a href="{url}"><img src="./assets/projects/{slug_}.svg" width="32%" '
                f'alt="{escape(title)} · {escape(domain)}" /></a>')
    rows = [PROJECTS[i:i + 3] for i in range(0, len(PROJECTS), 3)]
    return "\n".join("<p align=\"center\">\n  " + "\n  ".join(a(p) for p in row) + "\n</p>" for row in rows)


def links():
    def row(items):
        return "<p align=\"center\">\n" + "\n".join(
            f'  <a href="{url}"><img src="./badges/{s}.svg" height="40" alt="{label}" /></a>&nbsp;'
            for s, label, url in items) + "\n</p>"
    return row(LINKS[:4]) + "\n\n" + row(LINKS[4:])


